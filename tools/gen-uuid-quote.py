#!/usr/bin/env python3
"""Generate the internal UUID quoting helper from byte-pinned Go source tables.

--check compares deterministic bytes and writes nothing. This helper preserves
Go Quote for an internal first-nine-byte slice of valid UTF-8 Text; it is not a
public general-purpose quoting port. No SDK download or native execution occurs.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PIN = '022c8636110ebac86a9b88724cda168ed713c21f'
OUTPUT = ROOT / 'ports/google/uuid/quote.gooo'
SOURCE_ROOT = ROOT / 'third_party/google-uuid/provenance/go-stdlib'
SOURCES = [
    ('src/strconv/quote.go', 'quote.go.txt', '6602960ec8777de9926c1d02fbf5cb0828d4aefa38083865f4af17b6892c09a2'),
    ('src/strconv/isprint.go', 'isprint.go.txt', 'e6f4b35fbf38f9c9c8b251e5d3cf94daa880789cb89825f11f9734ba4a42e9ff'),
    ('LICENSE', 'GO-LICENSE', '911f8f5782931320f5b8d1160a76365b83aea6447ee6c04fa6d5591467db9dad'),
]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='compare existing source bytes without writing')
args = parser.parse_args()
records = []
for name, copy, expected in SOURCES:
    raw = (SOURCE_ROOT / copy).read_bytes()
    actual = hashlib.sha256(raw).hexdigest()
    if actual != expected:
        raise SystemExit('pinned Go source hash differs: ' + name)
    records.append({'source': name, 'copy': str((SOURCE_ROOT / copy).relative_to(ROOT)),
                    'bytes': len(raw), 'sha256': actual})
table = (SOURCE_ROOT / 'isprint.go.txt').read_text()
def array(name):
    text = re.search(r'var ' + name + r' = \[\]uint(?:16|32)\{(.*?)\n\}', table, re.S)[1]
    text = re.sub(r'//[^\n]*', '', text)
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', text)]

def split_ranges(bounds, excluded):
    assert len(bounds) % 2 == 0
    result = []
    for low, high in zip(bounds[::2], bounds[1::2]):
        at = low
        for hole in excluded:
            if low <= hole <= high:
                if at < hole:
                    result.append((at, hole - 1))
                at = hole + 1
        if at <= high:
            result.append((at, high))
    return result

ranges = split_ranges(array('isPrint16'), array('isNotPrint16'))
ranges += split_ranges(array('isPrint32'), [n + 65536 for n in array('isNotPrint32')])
# Preserve the explicit Latin-1 fast path in quote.go.
ranges = [(max(low, 256), high) for low, high in ranges if high >= 256]
ranges += [(32, 126), (161, 172), (174, 255)]
ranges.sort()
merged = []
for low, high in ranges:
    if merged and low <= merged[-1][1] + 1:
        merged[-1] = (merged[-1][0], max(high, merged[-1][1]))
    else:
        merged.append((low, high))
assert all(0 <= low <= high <= 1114111 for low, high in merged)

def tree(rows, indent=''):
    if len(rows) == 1:
        low, high = rows[0]
        return indent + f'return input >= {low} && input <= {high}\n'
    mid = len(rows) // 2
    return (indent + f'if input < {rows[mid][0]} {{\n' + tree(rows[:mid], indent + '    ')
            + indent + '} else {\n' + tree(rows[mid:], indent + '    ') + indent + '}\n')

notice = '''// Copyright 2009 The Go Authors. All rights reserved.
// Copyright 2013 The Go Authors. All rights reserved.
// Use of this source code is governed by the BSD-style license reproduced
// in third_party/google-uuid/provenance/go-stdlib/GO-LICENSE.
// Adapted from pinned Go 1.27.2 strconv quoting.
// Generated by tools/gen-uuid-quote.py. Internal implementation for UUID;
// this helper is not a separately counted port or a general Go-string API.
// Input is valid UTF-8 Text. Exactly min(9, byte length) input bytes are quoted.
// A prefix-truncated UTF-8 rune is emitted one byte at a time as lowercase \\x.
// Printable complete runes retain their original UTF-8 bytes; all other runes
// use Go Quote's escape policy. No formatting selector or oracle is executed.
package uuidquote
namespace gooo_google_uuid_quote

entity Text id "gooo://std/text"
entity Integer id "gooo://std/integer"
entity Boolean id "gooo://std/boolean"

'''
for record in records:
    notice = '// SHA256 ' + record['source'] + ' ' + record['sha256'] + '\n' + notice

source = notice + 'activity IsPrintable(Integer) -> Boolean id "gooo://github.com/google/uuid/internal/quote/is-printable" computes `'
source += 'if input < 0 || input > 1114111 { return false }\n' + '\n'.join(line.lstrip() for line in tree(merged).splitlines()) + '`\n\n'
source += '''activity HexDigit(Integer) -> Text id "gooo://github.com/google/uuid/internal/quote/hex-digit" computes `if input < 0 || input > 15 { return "" }
let digits = "0123456789abcdef"
return digits[input:input+1]`

activity Hex2(Integer) -> Text id "gooo://github.com/google/uuid/internal/quote/hex2" computes `return HexDigit(input / 16 % 16) + HexDigit(input % 16)`

activity Hex4(Integer) -> Text id "gooo://github.com/google/uuid/internal/quote/hex4" computes `return HexDigit(input / 4096 % 16) + HexDigit(input / 256 % 16) + Hex2(input)`

activity Hex8(Integer) -> Text id "gooo://github.com/google/uuid/internal/quote/hex8" computes `return HexDigit(input / 268435456 % 16) + HexDigit(input / 16777216 % 16) + HexDigit(input / 1048576 % 16) + HexDigit(input / 65536 % 16) + Hex4(input)`

'''
source += r'''activity QuotePrefix9(Text) -> Text id "gooo://github.com/google/uuid/internal/quote/quote-prefix9" computes `let limit = int64(len(input))
if limit > 9 { limit = 9 }
let output = "\""
let offset = 0
let step = 0
for step = 0; step < 9; step = step + 1 {
    if offset >= limit { return output + "\"" }
    let first = int64(input[offset])
    let width = 1
    if first >= 194 && first <= 223 { width = 2 }
    if first >= 224 && first <= 239 { width = 3 }
    if first >= 240 && first <= 244 { width = 4 }
    if first >= 128 && (width == 1 || offset + width > limit) {
        output = output + "\\x" + Hex2(first)
        offset = offset + 1
    } else {
        let code = first
        if width == 2 {
            let second = int64(input[offset + 1])
            code = (first - 192) * 64 + second - 128
        }
        if width == 3 {
            let second = int64(input[offset + 1])
            let third = int64(input[offset + 2])
            code = (first - 224) * 4096 + (second - 128) * 64 + third - 128
        }
        if width == 4 {
            let second = int64(input[offset + 1])
            let third = int64(input[offset + 2])
            let fourth = int64(input[offset + 3])
            code = (first - 240) * 262144 + (second - 128) * 4096 + (third - 128) * 64 + fourth - 128
        }
        if code == 34 || code == 92 {
            output = output + "\\" + input[offset:offset + width]
        } else {
            if IsPrintable(code) {
                output = output + input[offset:offset + width]
            } else {
                if code == 7 { output = output + "\\a" } else {
                if code == 8 { output = output + "\\b" } else {
                if code == 12 { output = output + "\\f" } else {
                if code == 10 { output = output + "\\n" } else {
                if code == 13 { output = output + "\\r" } else {
                if code == 9 { output = output + "\\t" } else {
                if code == 11 { output = output + "\\v" } else {
                    if code < 32 || code == 127 {
                        output = output + "\\x" + Hex2(code)
                    } else {
                        if code < 65536 {
                            output = output + "\\u" + Hex4(code)
                        } else {
                            output = output + "\\U" + Hex8(code)
                        }
                    }
                }}}}}}}
            }
        }
        offset = offset + width
    }
}
return output + "\""`
'''
# Python raw source above uses escaped declaration quotes for readability.
# Body strings must retain their backslash escapes; only declaration quotes differ.
source = source.replace(r'id \"gooo://github.com/google/uuid/internal/quote/quote-prefix9\"', 'id "gooo://github.com/google/uuid/internal/quote/quote-prefix9"')
generated = source.encode('utf-8')
if len(generated) > 65536:
    raise SystemExit('internal quoting source exceeds the supported body-codegen source bound')
if args.check:
    if not OUTPUT.is_file() or OUTPUT.read_bytes() != generated:
        raise SystemExit('generated UUID quote helper differs: ' + str(OUTPUT.relative_to(ROOT)))
else:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_bytes(generated)
print(json.dumps({'schema': 'gooo/google-uuid-quote-generator/v1', 'go_version': 'go1.27.2',
                  'go_revision': PIN, 'sources': records, 'printable_intervals': len(merged),
                  'table_arrays': {name: len(array(name)) for name in ['isPrint16', 'isNotPrint16', 'isPrint32', 'isNotPrint32']},
                  'source_sha256': hashlib.sha256(generated).hexdigest(), 'source_bytes': len(generated),
                  'mode': 'check' if args.check else 'generate', 'separate_public_port': False},
                 separators=(',', ':')))
