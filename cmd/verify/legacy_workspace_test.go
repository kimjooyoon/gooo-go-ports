// This fixture was produced by the unchanged verifier/catalog/corpus from
// immutable Git commit 445eb4835a6eedc37a597aafdb949948a4e65d5b, under Go 1.27.2.
// Its generator ran one ordinary Go test in a plain Git-blob source snapshot;
// it did not run the compiler or native verifier. It includes original source
// bytes, complete manifests, serialized input/case hashes and every boundary.
// The gzip is only storage compression; the fixed digest below binds all of the
// decompressed bytes. Expectations are never generated by the new selector.
const legacy445FixtureSHA256 = "sha256:42c492ac4d56bda7cb73731b22c9805dc38875794b42af797eb1613a957a46f6"

type legacy445Fixture struct {
	Schema    string            `json:"schema"`
	Commit    string            `json:"commit"`
	Tree      string            `json:"tree"`
	GoVersion string            `json:"go_version"`
	Catalog   []byte            `json:"catalog_bytes"`
	Sources   []legacy445Source `json:"sources"`
	Suites    []legacy445Suite  `json:"suites"`
	Cases     int               `json:"cases"`
	Batches   int               `json:"batches"`
}
type legacy445Source struct {
	Name     string         `json:"name"`
	Bytes    []byte         `json:"bytes"`
	SHA256   string         `json:"raw_sha256"`
	Identity sourceIdentity `json:"identity"`
}
type legacy445Suite struct {
	Package        string                    `json:"package"`
	Activity       string                    `json:"activity"`
	Domain         string                    `json:"domain"`
	Cases          int                       `json:"cases"`
	SuiteSHA256    string                    `json:"suite_sha256"`
	InputsSHA256   string                    `json:"inputs_sha256"`
	CaseFileSHA256 string                    `json:"case_file_sha256"`
	CaseFileBytes  int                       `json:"case_file_bytes"`
	Manifest       []byte                    `json:"manifest_bytes"`
	Names          []string                  `json:"source_names"`
	Identities     map[string]sourceIdentity `json:"source_identities"`
	RowLimit       int                       `json:"row_limit"`
	Batches        []legacy445Batch          `json:"batches"`
}
type legacy445Batch struct {
	Start  int    `json:"start"`
	End    int    `json:"end"`
	Bytes  int    `json:"case_file_bytes"`
	SHA256 string `json:"case_file_sha256"`
}

func legacy445SavedJSON(v any) ([]byte, error) {
	raw, err := json.MarshalIndent(v, "", "  ")
	return append(raw, '\n'), err
}

func loadLegacy445Fixture(t *testing.T) legacy445Fixture {
	t.Helper()
	packed, err := os.ReadFile("testdata/legacy-main445.json.gz")
	if err != nil {
		t.Fatal(err)
	}
	r, err := gzip.NewReader(bytes.NewReader(packed))
	if err != nil {
		t.Fatal(err)
	}
	raw, err := io.ReadAll(io.LimitReader(r, 2<<20))
	closeErr := r.Close()
	if err != nil || closeErr != nil {
		t.Fatal(err, closeErr)
	}
	if contentDigest(raw) != legacy445FixtureSHA256 {
		t.Fatal("immutable main445 fixture digest differs")
	}
	var fixture legacy445Fixture
	if err := json.Unmarshal(raw, &fixture); err != nil {
		t.Fatal(err)
	}
	if fixture.Schema != "gooo/main445-legacy-verifier-fixture/v1" || fixture.Commit != "445eb4835a6eedc37a597aafdb949948a4e65d5b" || fixture.Tree != "aba286410fa8a9c23e4bc885fbd39489d6f5c7ae" || fixture.GoVersion != "go1.27.2" || len(fixture.Suites) != 59 || len(fixture.Sources) != 37 || fixture.Cases != 131842 || fixture.Batches != 1777 {
		t.Fatal("immutable main445 fixture identity or counts differ")
	}
	return fixture
}

func inspectLegacy445Suite(s suite, w suiteWorkspace, want legacy445Suite, sources map[string]legacy445Source) error {
	if s.Package != want.Package || s.Activity != want.Activity || s.Domain != want.Domain || len(s.Cases) != want.Cases {
		return fmt.Errorf("suite identity/domain/count differs from main445")
	}
	raw, err := json.Marshal(s)
	if err != nil || contentDigest(raw) != want.SuiteSHA256 {
		return fmt.Errorf("complete serialized suite differs from main445: %v", err)
	}
	var inputs [][]any
	for _, c := range s.Cases {
		inputs = append(inputs, c.Inputs)
	}
	raw, err = json.Marshal(inputs)
	if err != nil || contentDigest(raw) != want.InputsSHA256 {
		return fmt.Errorf("ordered serialized inputs differ from main445: %v", err)
	}
	raw, err = legacy445SavedJSON(caseDocument(s))
	if err != nil || len(raw) != want.CaseFileBytes || contentDigest(raw) != want.CaseFileSHA256 {
		return fmt.Errorf("serialized case document differs from main445: %v", err)
	}
	raw, err = legacy445SavedJSON(w.Manifest)
	if err != nil || !bytes.Equal(raw, want.Manifest) {
		return fmt.Errorf("complete execution manifest differs from main445: %v", err)
	}
	if !reflect.DeepEqual(w.Names, want.Names) || !reflect.DeepEqual(w.Identities, want.Identities) || len(w.Sources) != len(want.Names) {
		return fmt.Errorf("ordered source roster or identities differ from main445")
	}
	for _, name := range want.Names {
		old, exists := sources[name]
		raw, selected := w.Sources[name]
		if !exists || !selected || !bytes.Equal(raw, old.Bytes) || contentDigest(raw) != old.SHA256 || w.Identities[name] != old.Identity {
			return fmt.Errorf("source bytes or hashes differ from main445: %s", name)
		}
	}
	if nativeBatchSize(s) != want.RowLimit {
		return fmt.Errorf("native row limit differs from main445")
	}
	var batches []legacy445Batch
	for start := 0; start < len(s.Cases); {
		end, err := nativeBatchEnd(s, start, want.RowLimit)
		if err != nil {
			return err
		}
		batch := s
		batch.Cases = s.Cases[start:end]
		raw, err := legacy445SavedJSON(caseDocument(batch))
		if err != nil {
			return err
		}
		batches = append(batches, legacy445Batch{start, end, len(raw), contentDigest(raw)})
		start = end
	}
	if !reflect.DeepEqual(batches, want.Batches) {
		return fmt.Errorf("batch boundaries or serialized batch files differ from main445")
	}
	return nil
}

// Recheck the historical selector against its original source bytes. The
// current snapshot must contain the one exact reviewed quote revision; only
// the owned historical projection replaces it with the immutable fixture bytes.
// This does not establish current-source native equivalence or rewrite history.
func legacy445HistoricalSnapshot(t *testing.T, current frozenVerificationCatalog, fixture legacy445Fixture) frozenVerificationCatalog {
	t.Helper()
	const quote = "ports/google/uuid/quote.gooo"
	const historicalQuote = "b9b0a9d642a91e2baba25b7636e875f6e5de9713bb7c4913368cd564cf34e339"
	const reviewedCurrentQuote = "3a14a762ceed11df29b698ab3eb298655a6737bbba76fe5dbb38dbc81baeb7de"
	if contentDigest(current.Sources[quote]) != "sha256:"+reviewedCurrentQuote || current.Hashes[quote] != reviewedCurrentQuote {
		t.Fatal("current quote differs from the exact reviewed revision")
	}
	currentQuote := bytes.Clone(current.Sources[quote])
	historical := current
	historical.Sources = make(map[string][]byte, len(current.Sources))
	historical.Hashes = make(map[string]string, len(current.Hashes))
	for name, raw := range current.Sources {
		historical.Sources[name] = bytes.Clone(raw)
	}
	for name, digest := range current.Hashes {
		historical.Hashes[name] = digest
	}
	found := false
	for _, original := range fixture.Sources {
		if original.Name != quote {
			continue
		}
		if found || original.SHA256 != "sha256:"+historicalQuote || contentDigest(original.Bytes) != original.SHA256 {
			t.Fatal("immutable fixture quote differs from its original revision")
		}
		found = true
		historical.Sources[quote] = bytes.Clone(original.Bytes)
		historical.Hashes[quote] = historicalQuote
	}
	if !found || !bytes.Equal(current.Sources[quote], currentQuote) || current.Hashes[quote] != reviewedCurrentQuote {
		t.Fatal("missing historical quote or projection mutated the current snapshot")
	}
	return historical
}

func TestLegacy445HistoricalSnapshotCatalogSourcesManifestsInputsCasesAndBatchesRemainIdentical(t *testing.T) {
	fixture := loadLegacy445Fixture(t)
	current, err := freezeVerificationCatalog("../../verification-catalog.json")
	if err != nil {
		t.Fatal(err)
	}
	var expectedCatalog verificationCatalog
	if err := json.Unmarshal(fixture.Catalog, &expectedCatalog); err != nil {
		t.Fatal(err)
	}
	if contentDigest(fixture.Catalog) != "sha256:6c5083d292df0127d74c76b58a21aef0d7619e5db18dd19b45a58a907417017f" {
		t.Fatal("main445 catalog bytes differ")
	}
	for i := range expectedCatalog.Packages {
		if expectedCatalog.Packages[i].Path == "go/strings" {
			expectedCatalog.Packages[i].Sources = append(expectedCatalog.Packages[i].Sources, "ports/strings/literal.gooo", "ports/strings/cut.gooo")
		}
	}
	expectedCatalog.Packages = append(expectedCatalog.Packages, sourcePackage{Path: "app/literal-text-report", Sources: []string{"examples/literal-text-report/main.gooo"}})
	expectedCatalog.Packages = append(expectedCatalog.Packages,
		sourcePackage{Path: "go/cel.dev/cel-go/codelab", Sources: []string{"ports/cel/scalar_access.gooo"}},
		sourcePackage{Path: "app/cel-api-policy", Sources: []string{"examples/cel-api-policy/main.gooo"}},
		sourcePackage{Path: "go/google/agentmesh/api", Sources: []string{"ports/agentmesh/service_pattern.gooo"}},
		sourcePackage{Path: "app/service-grant-impact", Sources: []string{"examples/agentmesh-service-policy/impact.gooo"}},
		sourcePackage{Path: "app/service-grant-refinement", Sources: []string{"examples/agentmesh-service-policy/refinement.gooo"}},
		sourcePackage{Path: "gooo/service-domain", Sources: []string{"examples/agentmesh-service-policy/domain.gooo"}},
		sourcePackage{Path: "gooo/service-policy/checked-matcher", Sources: []string{"examples/agentmesh-service-policy/checked_matcher.gooo"}},
		sourcePackage{Path: "gooo/service-policy/checked-impact", Sources: []string{"examples/agentmesh-service-policy/checked_impact.gooo"}},
		sourcePackage{Path: "gooo/service-policy/checked-refinement", Sources: []string{"examples/agentmesh-service-policy/checked_refinement.gooo"}},
		sourcePackage{Path: "gooo/service-policy/conditional-apply", Sources: []string{"examples/agentmesh-service-policy/conditional_apply.gooo"}},
		sourcePackage{Path: "app/literal-cut-report", Sources: []string{"examples/literal-cut-report/main.gooo"}},
		sourcePackage{Path: "go/strconv", Sources: []string{"ports/strconv/decimal.gooo"}},
		sourcePackage{Path: "app/payload-admission", Sources: []string{"examples/payload-admission/main.gooo"}},
		sourcePackage{Path: "go/path", Sources: []string{"ports/path/path.gooo", "ports/path/clean.gooo"}},
		sourcePackage{Path: "app/path-alias-facts", Sources: []string{"examples/path-alias-facts/main.gooo"}},
		sourcePackage{Path: headerPortPackage, Sources: []string{headerPortSource}},
		sourcePackage{Path: headerReportPackage, Sources: []string{headerReportSource}},
		sourcePackage{Path: headerAdditionPackage, Sources: []string{headerAdditionSource}},
		sourcePackage{Path: canonicalHeaderPackage, Sources: []string{canonicalHeaderSource}},
		sourcePackage{Path: canonicalHeaderReportPackage, Sources: []string{canonicalHeaderReportSource}},
		sourcePackage{Path: etagPortPackage, Sources: []string{etagPortSource}},
		sourcePackage{Path: etagReportPackage, Sources: []string{etagReportSource}},
		sourcePackage{Path: ifMatchPackage, Sources: []string{ifMatchSource}},
	)
	if !reflect.DeepEqual(current.Catalog, expectedCatalog) || len(current.Sources) != len(fixture.Sources)+27 {
		t.Fatal("catalog changed beyond the reviewed literal, Cut, CEL, AgentMesh, checked-domain, conditional-apply, decimal/payload, path Clean/alias, header, original header-addition, canonical-key/report and ETag/strong-validator-facts sources")
	}
	historical := legacy445HistoricalSnapshot(t, current, fixture)
	sources := map[string]legacy445Source{}
	for _, old := range fixture.Sources {
		if !bytes.Equal(historical.Sources[old.Name], old.Bytes) || contentDigest(historical.Sources[old.Name]) != old.SHA256 {
			t.Fatal("original catalog source bytes changed", old.Name)
		}
		sources[old.Name] = old
	}
	suites := original59NativeSuites(t)
	if len(suites) != len(fixture.Suites) {
		t.Fatal("original59 roster differs")
	}
	cases, batches := 0, 0
	for i, s := range suites {
		t.Run(s.Package+":"+s.Activity, func(t *testing.T) {
			w, err := historical.workspaceForSuite(s)
			if err != nil {
				t.Fatal(err)
			}
			if err := inspectLegacy445Suite(s, w, fixture.Suites[i], sources); err != nil {
				t.Fatal(err)
			}
			if _, exists := w.Sources["ports/strings/literal.gooo"]; exists {
				t.Fatal("literal source leaked into old suite")
			}
			if _, exists := w.Sources["examples/literal-text-report/main.gooo"]; exists {
				t.Fatal("literal consumer leaked into old suite")
			}
			if _, exists := w.Sources["ports/strings/cut.gooo"]; exists {
				t.Fatal("Cut source leaked into old suite")
			}
			if _, exists := w.Sources["examples/literal-cut-report/main.gooo"]; exists {
				t.Fatal("Cut consumer leaked into old suite")
			}
		})
		cases += len(s.Cases)
		batches += len(fixture.Suites[i].Batches)
	}
	if cases != 131842 || batches != 1777 {
		t.Fatal("original59 totals differ", cases, batches)
	}
}

func TestLegacy445HistoricalSnapshotRegressionEvidenceRejectsChanges(t *testing.T) {
	fixture := loadLegacy445Fixture(t)
	current, err := freezeVerificationCatalog("../../verification-catalog.json")
	if err != nil {
		t.Fatal(err)
	}
	historical := legacy445HistoricalSnapshot(t, current, fixture)
	s := original59NativeSuites(t)[0]
	w, err := historical.workspaceForSuite(s)
	if err != nil {
		t.Fatal(err)
	}
	sources := map[string]legacy445Source{}
	for _, old := range fixture.Sources {
		sources[old.Name] = old
	}
	for name, mutate := range map[string]func(*suite, *suiteWorkspace, *legacy445Suite){
		"original input":  func(s *suite, _ *suiteWorkspace, _ *legacy445Suite) { s.Cases[0].Inputs = []any{int64(999)} },
		"reference value": func(s *suite, _ *suiteWorkspace, _ *legacy445Suite) { s.Cases[0].Expected = "changed" },
		"domain":          func(s *suite, _ *suiteWorkspace, _ *legacy445Suite) { s.Domain += " changed" },
		"manifest source order": func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) {
			w.Manifest.Packages[0], w.Manifest.Packages[1] = w.Manifest.Packages[1], w.Manifest.Packages[0]
		},
		"source name order": func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) { w.Names[0], w.Names[1] = w.Names[1], w.Names[0] },
		"source bytes":      func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) { w.Sources[w.Names[0]] = []byte("changed") },
		"source owner": func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) {
			old := w.Identities[w.Names[0]]
			old.Package = "other"
			w.Identities[w.Names[0]] = old
		},
		"source digest": func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) {
			old := w.Identities[w.Names[0]]
			old.Digest = contentDigest([]byte("changed"))
			w.Identities[w.Names[0]] = old
		},
		"extra consumer": func(_ *suite, w *suiteWorkspace, _ *legacy445Suite) {
			w.Sources["examples/literal-text-report/main.gooo"] = historical.Sources["examples/literal-text-report/main.gooo"]
		},
		"batch boundary":   func(_ *suite, _ *suiteWorkspace, want *legacy445Suite) { want.Batches[0].End++ },
		"batch byte count": func(_ *suite, _ *suiteWorkspace, want *legacy445Suite) { want.Batches[0].Bytes++ },
		"batch serialized bytes": func(_ *suite, _ *suiteWorkspace, want *legacy445Suite) {
			want.Batches[0].SHA256 = contentDigest([]byte("changed"))
		},
	} {
		t.Run(name, func(t *testing.T) {
			candidate := s
			candidate.Cases = append([]testCase(nil), s.Cases...)
			selected, err := historical.workspaceForSuite(s)
			if err != nil {
				t.Fatal(err)
			}
			want := fixture.Suites[0]
			want.Batches = append([]legacy445Batch(nil), want.Batches...)
			mutate(&candidate, &selected, &want)
			if err := inspectLegacy445Suite(candidate, selected, want, sources); err == nil {
				t.Fatal("accepted changed original59 evidence")
			}
		})
	}
	if err := inspectLegacy445Suite(s, w, fixture.Suites[0], sources); err != nil {
		t.Fatal("rejection test mutated its baseline", err)
	}
}
