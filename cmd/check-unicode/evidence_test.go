func TestJSONIntegersPreservePrecision(t *testing.T) {
	if sameJSON([]byte("9223372036854775807"), []byte("9223372036854775806")) {
		t.Fatal("int64 values collapsed")
	}
	if sameJSON([]byte("1 2"), []byte("1")) {
		t.Fatal("accepted trailing JSON")
	}
}

func marshal(t *testing.T, v any) []byte {
	t.Helper()
	b, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

