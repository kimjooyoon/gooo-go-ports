func TestCompilerIdentityRejections(t *testing.T) {
	lock := lockfile{GoVersion: "go1.27.2", CompilerRevision: "pinned", CompilerVersion: "0.6.24-dev"}
	valid := buildIdentity{"gooo/build-identity/v1", "pinned", "0.6.24-dev", "go1.27.2", "go1.27.2", "false", "CLEAN_VCS"}
	if err := checkCompiler(marshal(t, valid), lock); err != nil {
		t.Fatal(err)
	}
	for name, mutate := range map[string]func(*buildIdentity){
		"wrong revision":         func(b *buildIdentity) { b.Revision = "other" },
		"wrong compiler version": func(b *buildIdentity) { b.Version = "other" },
		"wrong build toolchain":  func(b *buildIdentity) { b.Go = "go1.27.1" },
		"wrong native toolchain": func(b *buildIdentity) { b.Native = "go1.27.1" },
		"modified":               func(b *buildIdentity) { b.Modified = "true" },
		"unknown source":         func(b *buildIdentity) { b.Status = "UNKNOWN" },
	} {
		t.Run(name, func(t *testing.T) {
			b := valid
			mutate(&b)
			if checkCompiler(marshal(t, b), lock) == nil {
				t.Fatal("accepted wrong compiler")
			}
		})
	}
}

func TestReceiptBindingsRejectPlausiblePass(t *testing.T) {
	valid, bind := fixture(t)
	if _, _, err := inspectReceipt(marshal(t, valid), bind, ""); err != nil {
		t.Fatal(err)
	}
	mutations := map[string]func(*receipt){
		"manifest":              func(e *receipt) { e.ManifestDigest = "sha256:other" },
		"cases":                 func(e *receipt) { e.CasesDigest = "sha256:other" },
		"source":                func(e *receipt) { e.Result.Program.Image.Packages[0].Sources[0].Digest = "sha256:other" },
		"source owner":          func(e *receipt) { e.Result.Program.Image.Packages[0].Path = "unrelated" },
		"entry package":         func(e *receipt) { e.Result.Program.Entry.Package = "unrelated" },
		"entry activity":        func(e *receipt) { e.Result.Program.Entry.Activity = "Other" },
		"entry semantic id":     func(e *receipt) { e.Result.Program.Image.Packages[1].Exports[0].ID = "unrelated" },
		"port semantic id":      func(e *receipt) { e.Result.Program.Image.Packages[0].Exports[0].ID = "unrelated" },
		"producer":              func(e *receipt) { e.Result.Runtime.Producer = "wrong" },
		"go":                    func(e *receipt) { e.Result.Runtime.Go = "go version go1.27.1 darwin/arm64" },
		"trace input narrowing": func(e *receipt) { e.Result.Runtime.Traces[0].Deliveries[0].Input = json.RawMessage("65") },
		"trace output": func(e *receipt) {
			e.Result.Runtime.Traces[0].Deliveries[0].Actual = json.RawMessage(`{"in_rune_domain":true}`)
		},
		"trace expected":        func(e *receipt) { e.Result.Runtime.Traces[0].Deliveries[0].Expected = json.RawMessage(`false`) },
		"trace entry":           func(e *receipt) { e.Result.Runtime.Traces[0].Deliveries[0].ID = letterID },
		"record field identity": func(e *receipt) { e.Result.Runtime.Traces[0].Deliveries[0].Fields[0].ID = "wrong" },
		"field value":           func(e *receipt) { e.Result.Runtime.Traces[0].Deliveries[0].Fields[0].Value = json.RawMessage("true") },
		"generated bytes":       func(e *receipt) { e.Result.Composition.Source += "\n" },
		"generated producer":    func(e *receipt) { e.Result.Composition.Steps[0].Generation.Report.Producer = "other" },
		"plan entry":            func(e *receipt) { e.Result.Composition.Plan.Activities[0].ID = letterID },
		"closure callee":        func(e *receipt) { e.Result.Composition.Steps[0].Generation.Report.Closure.Edges[0].Callee = "wrong" },
		"closure ordinal":       func(e *receipt) { e.Result.Composition.Steps[0].Generation.Report.Closure.Edges[0].Ordinal = 1 },
		"swapped closure activities only": func(e *receipt) {
			activities := e.Result.Composition.Steps[0].Generation.Report.Closure.Activities
			activities[0], activities[1] = activities[1], activities[0]
		},
		"swapped closure edge callees": func(e *receipt) {
			edges := e.Result.Composition.Steps[0].Generation.Report.Closure.Edges
			edges[0].Callee, edges[1].Callee = edges[1].Callee, edges[0].Callee
		},
		"model calls":   func(e *receipt) { n := 1; e.Result.Runtime.Calls = &n },
		"false replay":  func(e *receipt) { e.Result.Runtime.Replayed = false },
		"missing trace": func(e *receipt) { e.Result.Runtime.Traces = nil },
	}
	for name, mutate := range mutations {
		t.Run(name, func(t *testing.T) {
			var e receipt
			if err := json.Unmarshal(marshal(t, valid), &e); err != nil {
				t.Fatal(err)
			}
			mutate(&e)
			if _, _, err := inspectReceipt(marshal(t, e), bind, ""); err == nil {
				t.Fatal("accepted invalid PASS evidence")
			}
		})
	}
}

func TestSavedReplayBinding(t *testing.T) {
	e, b := fixture(t)
	original := sha(marshal(t, e))
	zero := 0
	e.ReplayedFrom = original
	e.Result.Replay = &struct {
		Calls *int `json:"model_calls"`
	}{&zero}
	if _, _, err := inspectReceipt(marshal(t, e), b, original); err != nil {
		t.Fatal(err)
	}
	if _, _, err := inspectReceipt(marshal(t, e), b, "sha256:wrong"); err == nil {
		t.Fatal("accepted wrong saved receipt")
	}
	e.Result.Replay = nil
	if _, _, err := inspectReceipt(marshal(t, e), b, original); err == nil {
		t.Fatal("accepted missing replay")
	}
}

func TestGeneratedASTRejectsWrongEntry(t *testing.T) {
	e, b := fixture(t)
	for name, change := range map[string]func(string) string{
		"wrong parameter":     func(s string) string { return strings.Replace(s, "input int64", "input float64", 1) },
		"missing helper call": func(s string) string { return strings.Replace(s, "EntryCall0(input)", "true", 1) },
		"swapped source call slots": func(s string) string {
			s = strings.Replace(s, "EntryCall0(input)", "TemporaryCall(input)", 1)
			s = strings.Replace(s, "EntryCall1(input)", "EntryCall0(input)", 1)
			return strings.Replace(s, "TemporaryCall(input)", "EntryCall1(input)", 1)
		},
		"changed helper input": func(s string) string { return strings.Replace(s, "EntryCall0(input)", "EntryCall0(65)", 1) },
		"wrong field tag":      func(s string) string { return strings.Replace(s, "json:\"can_start\"", "json:\"wrong\"", 1) },
		"extra function":       func(s string) string { return s + "\nfunc init() {}\n" },
	} {
		t.Run(name, func(t *testing.T) {
			c := e.Result.Composition
			c.Source = change(c.Source)
			if _, err := inspectGenerated(c, b.Lock.CompilerRevision); err == nil {
				t.Fatal("accepted invalid generated AST")
			}
		})
	}
}

