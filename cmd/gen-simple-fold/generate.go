package main

import (
	"fmt"
	"strings"
	"unicode"
)

type asciiRange struct{ lo, hi, delta int64 }

func generate(pin upstream, tables foldTables) ([]byte, error) {
	if err := validateTables(tables); err != nil {
		return nil, err
	}
	var out strings.Builder
	out.WriteString("// Copyright 2009 The Go Authors. All rights reserved.\n")
	out.WriteString("// Use of this source code is governed by a BSD-style\n// license that can be found in the LICENSE file.\n")
	out.WriteString("// Code generated by go run ./cmd/gen-simple-fold; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Go %s; Unicode %s; source revision %s.\n", strings.TrimPrefix(pin.GoVersion, "go"), pinnedUnicode, pin.GoRevision)
	out.WriteString("// Upstream license: third_party/GO-LICENSE.\n")
	for _, name := range requiredSources {
		fmt.Fprintf(&out, "// SHA256 %s %s\n", name, pin.SourceSHA[name])
	}
	out.WriteString("// Go rune is signed int32, represented exactly by Gooo Integer (int64).\n")
	out.WriteString("// Outside-int32 inputs return themselves as an explicit extension; no narrowing.\n")
	out.WriteString("// Invalid Unicode code points also return themselves, as in Go SimpleFold.\n")
	out.WriteString("// ASCII table first, then special case orbits, then case-range lower/upper.\n")
	out.WriteString("// UpperLower parity is relative to each range's Lo, using arithmetic only.\n")
	out.WriteString("// Scalar declarations are shared with space.gooo in this package.\n")
	out.WriteString("package unicode\nnamespace gooo_ports_unicode\n\n")
	fmt.Fprintf(&out, "// Complete tables: %d ASCII entries, %d orbit pairs, %d case ranges.\n", len(tables.ascii), len(tables.orbit), len(tables.ranges))
	out.WriteString("activity SimpleFold(Integer) -> Integer id \"gooo://go/unicode/SimpleFold\" computes `")
	out.WriteString("if input < -2147483648 || input > 2147483647 { return input }\n")
	out.WriteString("if input < 0 || input > 1114111 { return input }\n")
	fmt.Fprintf(&out, "if input < %d {\n", len(tables.ascii))
	writeASCII(&out, asciiRanges(tables.ascii), 1)
	out.WriteString("\n}\n")
	writeOrbit(&out, tables.orbit, 0)
	out.WriteString("\n")
	writeCases(&out, tables.ranges, 0)
	out.WriteString("`\n")
	if out.Len() > 128<<10 {
		return nil, fmt.Errorf("generated Gooo exceeds the pinned compiler's 128 KiB source bound")
	}
	return []byte(out.String()), nil
}

// Compact consecutive ASCII entries with identical offsets. This reads the
// literal array; it does not assume ASCII letters have only two-member orbits.
func asciiRanges(table []int64) []asciiRange {
	var result []asciiRange
	for i, value := range table {
		delta := value - int64(i)
		if len(result) > 0 && result[len(result)-1].delta == delta {
			result[len(result)-1].hi = int64(i)
		} else {
			result = append(result, asciiRange{int64(i), int64(i), delta})
		}
	}
	return result
}

func writeASCII(out *strings.Builder, ranges []asciiRange, depth int) {
	indent := strings.Repeat("\t", depth)
	if len(ranges) == 1 {
		fmt.Fprintf(out, "%sreturn %s", indent, addDelta(ranges[0].delta))
		return
	}
	mid := len(ranges) / 2
	fmt.Fprintf(out, "%sif input < %d {\n", indent, ranges[mid].lo)
	writeASCII(out, ranges[:mid], depth+1)
	fmt.Fprintf(out, "\n%s} else {\n", indent)
	writeASCII(out, ranges[mid:], depth+1)
	fmt.Fprintf(out, "\n%s}", indent)
}

// A miss falls through to CaseRanges. Every hit returns immediately, including
// To==From: treating that self-orbit as a miss would change dotted/dotless I.
func writeOrbit(out *strings.Builder, pairs []foldPair, depth int) {
	indent := strings.Repeat("\t", depth)
	if len(pairs) == 1 {
		fmt.Fprintf(out, "%sif input == %d { return %d }", indent, pairs[0].from, pairs[0].to)
		return
	}
	mid := len(pairs) / 2
	fmt.Fprintf(out, "%sif input < %d {\n", indent, pairs[mid].from)
	writeOrbit(out, pairs[:mid], depth+1)
	fmt.Fprintf(out, "\n%s} else {\n", indent)
	writeOrbit(out, pairs[mid:], depth+1)
	fmt.Fprintf(out, "\n%s}", indent)
}

func writeCases(out *strings.Builder, ranges []caseRange, depth int) {
	indent := strings.Repeat("\t", depth)
	if len(ranges) == 1 {
		r := ranges[0]
		fmt.Fprintf(out, "%sif input < %d || input > %d { return input }\n", indent, r.lo, r.hi)
		if r.delta[unicode.LowerCase] == unicode.UpperLower {
			fmt.Fprintf(out, "%sif (input - %d) %% 2 == 0 { return input + 1 }\n%sreturn input - 1", indent, r.lo, indent)
			return
		}
		// A constant nonzero lower delta necessarily changes the rune. If it
		// is zero, Go tries upper instead; titlecase is not substituted here.
		delta := r.delta[unicode.LowerCase]
		if delta == 0 {
			delta = r.delta[unicode.UpperCase]
		}
		fmt.Fprintf(out, "%sreturn %s", indent, addDelta(delta))
		return
	}
	mid := len(ranges) / 2
	fmt.Fprintf(out, "%sif input < %d {\n", indent, ranges[mid].lo)
	writeCases(out, ranges[:mid], depth+1)
	fmt.Fprintf(out, "\n%s} else {\n", indent)
	writeCases(out, ranges[mid:], depth+1)
	fmt.Fprintf(out, "\n%s}", indent)
}

func addDelta(delta int64) string {
	if delta < 0 {
		return fmt.Sprintf("input - %d", -delta)
	}
	if delta > 0 {
		return fmt.Sprintf("input + %d", delta)
	}
	return "input"
}
