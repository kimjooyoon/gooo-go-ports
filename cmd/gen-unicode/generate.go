package main

import (
	"fmt"
	"strings"
	"unicode"
)

type interval struct{ lo, hi, stride int64 }

func tableIntervals(table *unicode.RangeTable) ([]interval, error) {
	if table == nil || len(table.R16)+len(table.R32) == 0 {
		return nil, fmt.Errorf("classification table is empty")
	}
	ranges := make([]interval, 0, len(table.R16)+len(table.R32))
	latin := 0
	for _, r := range table.R16 {
		ranges = append(ranges, interval{int64(r.Lo), int64(r.Hi), int64(r.Stride)})
		if r.Hi <= unicode.MaxLatin1 {
			latin++
		}
	}
	if table.LatinOffset != latin {
		return nil, fmt.Errorf("incorrect LatinOffset: got %d, want %d", table.LatinOffset, latin)
	}
	for _, r := range table.R32 {
		if r.Lo < 1<<16 {
			return nil, fmt.Errorf("R32 range starts below U+10000")
		}
		ranges = append(ranges, interval{int64(r.Lo), int64(r.Hi), int64(r.Stride)})
	}
	for i, r := range ranges {
		if r.lo > r.hi || r.hi > unicode.MaxRune || r.stride <= 0 {
			return nil, fmt.Errorf("invalid Unicode interval %d: %+v", i, r)
		}
		if i > 0 && ranges[i-1].hi >= r.lo {
			return nil, fmt.Errorf("Unicode intervals are unsorted or overlapping at %d", i)
		}
	}
	return ranges, nil
}

func generate(pin upstream, letters, digits *unicode.RangeTable) ([]byte, error) {
	var out strings.Builder
	out.WriteString("// Copyright 2009 The Go Authors. All rights reserved.\n")
	out.WriteString("// Copyright 2011 The Go Authors. All rights reserved.\n")
	out.WriteString("// Use of this source code is governed by a BSD-style\n// license that can be found in the LICENSE file.\n")
	out.WriteString("// Code generated by go run ./cmd/gen-unicode; DO NOT EDIT.\n")
	fmt.Fprintf(&out, "// Go %s; Unicode %s; source revision %s.\n", strings.TrimPrefix(pin.GoVersion, "go"), pinnedUnicode, pin.GoRevision)
	out.WriteString("// Upstream license: third_party/GO-LICENSE.\n")
	for _, name := range requiredSources {
		fmt.Fprintf(&out, "// SHA256 %s %s\n", name, pin.SourceSHA[name])
	}
	out.WriteString("// Complete pinned Letter (category L) and Digit (category Nd) tables.\n")
	out.WriteString("// Go rune is signed int32, represented exactly by Gooo Integer (int64).\n")
	out.WriteString("// Outside-int32 inputs return false as an explicit extension; no narrowing.\n")
	out.WriteString("// Scalar declarations are shared with space.gooo in this package.\n")
	out.WriteString("package unicode\nnamespace gooo_ports_unicode\n\n")
	for _, item := range []struct {
		name  string
		table *unicode.RangeTable
	}{{"IsLetter", letters}, {"IsDigit", digits}} {
		ranges, err := tableIntervals(item.table)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", item.name, err)
		}
		fmt.Fprintf(&out, "// %d R16 ranges and %d R32 ranges; each original stride is preserved.\n", len(item.table.R16), len(item.table.R32))
		fmt.Fprintf(&out, "activity %s(Integer) -> Boolean id \"gooo://go/unicode/%s\" computes `", item.name, item.name)
		out.WriteString("if input < -2147483648 || input > 2147483647 { return false }\n")
		out.WriteString("if input < 0 || input > 1114111 { return false }\n")
		writeTree(&out, ranges, 0)
		out.WriteString("`\n\n")
	}
	if out.Len() > 128<<10 {
		return nil, fmt.Errorf("generated Gooo source exceeds the pinned compiler's 128 KiB bound")
	}
	return []byte(out.String()), nil
}

func writeTree(out *strings.Builder, ranges []interval, depth int) {
	indent := strings.Repeat("\t", depth)
	if len(ranges) == 1 {
		r := ranges[0]
		fmt.Fprintf(out, "%sreturn input >= %d && input <= %d", indent, r.lo, r.hi)
		if r.stride != 1 {
			fmt.Fprintf(out, " && (input - %d) %% %d == 0", r.lo, r.stride)
		}
		return
	}
	mid := len(ranges) / 2
	fmt.Fprintf(out, "%sif input < %d {\n", indent, ranges[mid].lo)
	writeTree(out, ranges[:mid], depth+1)
	fmt.Fprintf(out, "\n%s} else {\n", indent)
	writeTree(out, ranges[mid:], depth+1)
	fmt.Fprintf(out, "\n%s}", indent)
}
