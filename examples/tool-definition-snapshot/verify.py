        host.save(out/'receipt-negative-controls.json',controls)
        payloads=None
        if args.write_generated:
            host.check_cancelled()
            e.same(before,snapshot(allow_missing_assets=True))
            provenance(generated,index_path,gofmt)
            payloads={name:e.read(generated/name,4<<20) for name in e.ASSETS}
            publish_generated_assets(payloads,summary['generated_write_records'])
