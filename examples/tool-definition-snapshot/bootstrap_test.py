"""Python-only controls for initial generated-file publication.

These use temporary synthetic files, never compiler/oracle execution or real
checked-in generation assets. Passing them is not native acceptance.
"""
import importlib.util
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

HERE=Path(__file__).resolve().parent
spec=importlib.util.spec_from_file_location('snapshot_bootstrap_verifier',HERE/'verify.py')
v=importlib.util.module_from_spec(spec);spec.loader.exec_module(v)

class BootstrapTests(unittest.TestCase):
    def setUp(self):
        self.temporary=tempfile.TemporaryDirectory(prefix='gooo-snapshot-bootstrap-test-')
        self.addCleanup(self.temporary.cleanup)
        self.root=Path(self.temporary.name)
        self.assets={'example/internal/kernel/'+name for name in ('projection.go','types.go','bridge.go')}|{'example/generation.json','example/cases.json'}
        self.payloads={name:('generated '+name).encode() for name in self.assets}
        self.patches=[patch.object(v,'ROOT',self.root),patch.object(v.e,'ASSETS',self.assets),patch.object(v,'HERE',self.root/'reference'),patch.object(v,'MODULE',self.root/'example'),patch.object(v.e,'MANIFEST',self.root/'workspace.json'),patch.object(v.e,'SOURCES',{'example':'source.gooo'})]
        for p in self.patches:p.start();self.addCleanup(p.stop)
        for name in ['upstream.json','workspace.json','source.gooo','examples/service-grant-many/verify.py','reference/reference.txt','example/adapter.go']:
            p=self.root/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_text('preserved '+name)

    def test_default_requires_all_assets(self):
        with self.assertRaises(AssertionError):v.snapshot()
        before=v.snapshot(allow_missing_assets=True)
        self.assertTrue(before)
        self.assertTrue(self.assets.isdisjoint(before))

    def test_one_existing_asset_blocks_bootstrap_before_any_write(self):
        name=sorted(self.assets)[-1];target=self.root/name
        target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(b'existing')
        journal=[]
        with self.assertRaisesRegex(AssertionError,'all five'):
            v.publish_generated_assets(self.payloads,journal)
        self.assertEqual(journal,[])
        self.assertEqual(target.read_bytes(),b'existing')
        self.assertEqual({n for n in self.assets if (self.root/n).exists()},{name})

    def test_dangling_target_symlink_blocks_bootstrap(self):
        target=self.root/sorted(self.assets)[0]
        target.parent.mkdir(parents=True,exist_ok=True);target.symlink_to(self.root/'does-not-exist')
        with self.assertRaisesRegex(AssertionError,'all five'):v.require_absent_assets()

    def test_exact_five_new_files_and_existing_source_preserved(self):
        before=v.snapshot(allow_missing_assets=True);journal=[]
        v.publish_generated_assets(self.payloads,journal)
        self.assertEqual(len(journal),5)
        self.assertTrue(all(record['completed'] for record in journal))
        after=v.snapshot();v.check_source_after(before,after,self.payloads)
        self.assertEqual(set(after)-set(before),self.assets)
        with self.assertRaisesRegex(AssertionError,'all five'):v.snapshot(allow_missing_assets=True)
        v.check_source_after(after,after)

    def test_source_mutation_is_not_hidden_by_generated_additions(self):
        before=v.snapshot(allow_missing_assets=True)
        v.publish_generated_assets(self.payloads,[])
        (self.root/'example/adapter.go').write_bytes(b'changed source')
        with self.assertRaises(AssertionError):v.check_source_after(before,v.snapshot(),self.payloads)

    def test_unrelated_new_file_is_refused(self):
        before=v.snapshot(allow_missing_assets=True)
        v.publish_generated_assets(self.payloads,[])
        (self.root/'example/unrelated.go').write_bytes(b'extra')
        with self.assertRaisesRegex(AssertionError,'only the five'):v.check_source_after(before,v.snapshot(),self.payloads)

    def test_generated_bytes_changed_after_write_are_refused(self):
        before=v.snapshot(allow_missing_assets=True)
        v.publish_generated_assets(self.payloads,[])
        (self.root/sorted(self.assets)[0]).write_bytes(b'tampered')
        with self.assertRaisesRegex(AssertionError,'generated bytes changed'):v.check_source_after(before,v.snapshot(),self.payloads)

    def test_exclusive_create_never_overwrites_a_racing_file(self):
        original=Path.open;target=self.root/sorted(self.assets)[0]
        def racing_open(path,mode='r',*args,**kwargs):
            if path==target and mode=='xb':
                with original(path,'wb') as output:output.write(b'other writer')
            return original(path,mode,*args,**kwargs)
        journal=[]
        with patch.object(Path,'open',racing_open):
            with self.assertRaises(FileExistsError):v.publish_generated_assets(self.payloads,journal)
        self.assertEqual(target.read_bytes(),b'other writer')
        self.assertEqual(len(journal),1)
        self.assertFalse(journal[0]['completed'])
        self.assertEqual({n for n in self.assets if (self.root/n).exists()},{sorted(self.assets)[0]})

if __name__=='__main__':unittest.main()
